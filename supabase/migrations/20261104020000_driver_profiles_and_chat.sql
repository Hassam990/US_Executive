begin;

create table if not exists public.driver_profiles (
    id uuid primary key default gen_random_uuid(),
    application_id text,
    driver_user_id text unique,
    display_name text not null check (char_length(display_name) between 2 and 120),
    headline text not null default '' check (char_length(headline) <= 140),
    bio text not null default '' check (char_length(bio) <= 1800),
    base_location text not null default '' check (char_length(base_location) <= 120),
    photo_url text check (photo_url is null or (photo_url like 'https://%' and char_length(photo_url) <= 500)),
    vehicle jsonb not null default '{}'::jsonb,
    services jsonb not null default '[]'::jsonb,
    status text not null default 'draft' check (status in ('draft', 'active', 'inactive')),
    is_public boolean not null default false,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now()
);

create index if not exists driver_profiles_public_idx
    on public.driver_profiles (status, is_public, display_name);

create table if not exists public.chat_conversations (
    id uuid primary key default gen_random_uuid(),
    conversation_type text not null check (conversation_type in ('support', 'driver')),
    driver_profile_id uuid references public.driver_profiles(id),
    visitor_name text not null default 'Website visitor' check (char_length(visitor_name) <= 100),
    visitor_email text check (visitor_email is null or char_length(visitor_email) <= 254),
    visitor_token_hash text not null,
    status text not null default 'open' check (status in ('open', 'closed')),
    created_at timestamptz not null default now(),
    last_message_at timestamptz not null default now(),
    constraint chat_conversation_driver_target_check check (
        (conversation_type = 'driver' and driver_profile_id is not null)
        or (conversation_type = 'support' and driver_profile_id is null)
    )
);

create index if not exists chat_conversations_recent_idx
    on public.chat_conversations (last_message_at desc);
create index if not exists chat_conversations_driver_idx
    on public.chat_conversations (driver_profile_id, last_message_at desc);

create table if not exists public.chat_messages (
    id bigint generated by default as identity primary key,
    conversation_id uuid not null references public.chat_conversations(id) on delete cascade,
    sender_role text not null check (sender_role in ('visitor', 'admin', 'driver', 'assistant')),
    body text not null check (char_length(btrim(body)) between 1 and 2000),
    created_at timestamptz not null default now()
);

create index if not exists chat_messages_conversation_idx
    on public.chat_messages (conversation_id, created_at);

alter table public.driver_profiles enable row level security;
alter table public.chat_conversations enable row level security;
alter table public.chat_messages enable row level security;

revoke all privileges on table public.driver_profiles, public.chat_conversations, public.chat_messages
    from public, anon, authenticated;
grant select, insert, update, delete on table public.driver_profiles, public.chat_conversations, public.chat_messages to service_role;
grant usage, select on sequence public.chat_messages_id_seq to service_role;

commit;
